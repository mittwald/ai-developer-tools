  C_DIM=''
  C_RED=''
  C_RESET=''
fi

# Colors of the status text (24-bit): mittwald blue, purple, salmon and rose.
# The colors flow through the letters. The part of the text that shows the
# elapsed share of the time limit is bold and in full color, the rest is muted.
# The attempt counter in front of the text stays dim, in the color of the theme.
GRADIENT_STOPS=(75 56 232  155 110 216  231 160 134  182 117 133)
GRADIENT_SIZE=60    # color steps of one cycle through all stops
MUTED_GRAY=125      # the muted colors are a mix with this gray
MUTED_PERCENT=62
BRIGHT=()
MUTED=()

# Fills BRIGHT and MUTED with one escape sequence per color step.
build_gradient() {
  local stops=$(( ${#GRADIENT_STOPS[@]} / 3 ))
  local step segment from to position ease channel value bright muted
  for ((step = 0; step < GRADIENT_SIZE; step++)); do
    segment=$(( step * stops / GRADIENT_SIZE ))
    from=$(( segment * 3 ))
    to=$(( (from + 3) % ${#GRADIENT_STOPS[@]} ))
    position=$(( step * stops % GRADIENT_SIZE * 1000 / GRADIENT_SIZE ))
    ease=$(( position * position * (3000 - 2 * position) / 1000000 ))
    bright=''
    muted=''
    for channel in 0 1 2; do
      value=$(( GRADIENT_STOPS[from + channel] + (GRADIENT_STOPS[to + channel] - GRADIENT_STOPS[from + channel]) * ease / 1000 ))
      bright+=";${value}"
      muted+=";$(( value + (MUTED_GRAY - value) * MUTED_PERCENT / 100 ))"
    done
    BRIGHT[step]=$'\033'"[0;1;38;2${bright}m"
    MUTED[step]=$'\033'"[0;38;2${muted}m"
  done
}

# Draws the status line. $1 = attempt counter, $2 = text, $3 = frame number,
# $4 = number of text characters in full color.
draw() {
  local text="$2"
  local length=${#2}
  local line=''
  local i step
  if [ "${COLOR}" -eq 1 ]; then
    line="${C_DIM}$1 "
    for ((i = 0; i < length; i++)); do
      step=$(( (i * GRADIENT_SIZE / length + GRADIENT_SIZE - $3 * 2 % GRADIENT_SIZE) % GRADIENT_SIZE ))
      if [ "${i}" -lt "$4" ]; then
        line+="${BRIGHT[step]}${text:i:1}"
      else
        line+="${MUTED[step]}${text:i:1}"
      fi
    done
    line+="${C_RESET}"
  else
    line="$1 ${text}"
  fi
  printf '\r%s\033[K' "${line}" >&2
}

# Replaces the status line with a final line. $1 = color, $2 = text.
finish() {
  if [ "${LIVE}" -eq 1 ]; then
    printf '\r\033[K' >&2
  fi
  printf '%s%s%s\n' "$1" "$2" "${C_RESET}" >&2
}

# Prints the last lines of cmai output. Control characters are removed, so that
# text from the API cannot send escape sequences to the terminal.
cmai_output() {
  local file
  for file in "${ERR_FILE}" "${OUT_FILE}"; do
    [ -s "${file}" ] || continue
    LC_ALL=C tr -d '\000-\010\013-\037\177' < "${file}" |
      grep -v '^[[:space:]]*$' | tail -n 3 | cut -c 1-300 | sed 's/^/  /'
    return
  done
}

# Reports why there is no generated message. $1 = reason, $2 = "details" to add
# the cmai output.
fail() {
  finish "${C_RED}" "No commit message generated: $1"
  if [ "${2:-}" = details ]; then
    cmai_output >&2
    if [ -n "${keychain_error}" ]; then
      printf '  %s\n' "${keychain_error}" >&2
    fi
  fi
  exit 0
}

# Prints the PowerShell script that prints a generic credential from the
# Windows Credential Manager. The name of the credential is in the environment
# variable CMAI_KEYCHAIN_TARGET.
windows_credential_script() {
  cat <<'POWERSHELL_EOF'
$ErrorActionPreference = 'Stop'
Add-Type -TypeDefinition @'
using System;
using System.Runtime.InteropServices;
public static class CmaiCredential {
  [StructLayout(LayoutKind.Sequential)]
  struct Credential {
    public uint Flags; public uint Type; public IntPtr TargetName; public IntPtr Comment;
    public System.Runtime.InteropServices.ComTypes.FILETIME LastWritten;
    public uint BlobSize; public IntPtr Blob; public uint Persist; public uint AttributeCount;
    public IntPtr Attributes; public IntPtr TargetAlias; public IntPtr UserName;
  }
  [DllImport("advapi32.dll", CharSet = CharSet.Unicode, SetLastError = true)]
  static extern bool CredReadW(string target, uint type, uint flags, out IntPtr credential);
  [DllImport("advapi32.dll")]
  static extern void CredFree(IntPtr credential);
  public static string Read(string target) {
    IntPtr pointer;
    if (!CredReadW(target, 1, 0, out pointer)) { return null; }
    try {
      Credential credential = (Credential)Marshal.PtrToStructure(pointer, typeof(Credential));
      return Marshal.PtrToStringUni(credential.Blob, (int)credential.BlobSize / 2);
    } finally { CredFree(pointer); }
  }
}
'@
$secret = [CmaiCredential]::Read($env:CMAI_KEYCHAIN_TARGET)
if ($null -eq $secret) { exit 1 }
[Console]::Out.Write($secret)
POWERSHELL_EOF
}

# Prints the API key from the system keychain. $1 = name of the keychain entry.
keychain_get() {
  local script
  case "${OSTYPE:-}" in
    darwin*)
      security find-generic-password -s "$1" -a "${KEYCHAIN_ACCOUNT}" -w
      ;;
    msys*|cygwin*)
      # -EncodedCommand takes the script as base64 of UTF-16, which needs no quoting.
      script="$(windows_credential_script | iconv -f UTF-8 -t UTF-16LE | base64 | tr -d '\r\n')"
      CMAI_KEYCHAIN_TARGET="$1" MSYS_NO_PATHCONV=1 MSYS2_ARG_CONV_EXCL='*' \
        powershell.exe -NoProfile -NonInteractive -EncodedCommand "${script}"
      ;;
    *)
      secret-tool lookup service "$1" account "${KEYCHAIN_ACCOUNT}"
      ;;
  esac
}

keychain_error=''

# git starts hooks with its own PATH, which can lack the directory of cmai.
CMAI="$(command -v cmai 2>/dev/null)" || CMAI="${HOME}/git-commit-ai/git-commit.sh"
[ -x "${CMAI}" ] || fail "cmai not found"

