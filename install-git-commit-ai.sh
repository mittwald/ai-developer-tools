check_requirements() {
  local tool hint
  local missing=()

  # cmai needs curl and jq to call the API.
  for tool in git curl jq; do
    command -v "${tool}" >/dev/null 2>&1 || missing+=("${tool}")
  done
  if [ "${#missing[@]}" -gt 0 ]; then
