parse_args() {
  while [ "$#" -gt 0 ]; do
    case "$1" in
      --non-interactive) non_interactive=1 ;;
      --repos)
        if [ "$#" -lt 2 ] || [ -z "$2" ]; then
          echo "${C_RED}ERROR:${C_RESET} --repos needs a directory" >&2
          usage >&2
          exit 1
        fi
        repo_dirs+=("$2")
        shift
        ;;
      -h|--help) usage; exit 0 ;;
      *)
        echo "${C_RED}ERROR:${C_RESET} unknown option: $1" >&2
        usage >&2
        exit 1
        ;;
    esac
    shift
  done
}

