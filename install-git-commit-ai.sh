# Old cmai versions take an unknown option as the API key and then run
# `git add .`. The check therefore reads the cmai script and does not run it.
cmai_is_current() {
  local cmai_path option
  hash -r
  cmai_path="$(command -v cmai 2>/dev/null)" || return 1
  [ -r "${cmai_path}" ] || return 1
  for option in "${CMAI_REQUIRED_OPTIONS[@]}"; do
    grep -qF -e "${option})" "${cmai_path}" || return 1
  done
}

# Prints one line for each thing in a downloaded cmai script that does not look
# like cmai. $1 = script file. The script is read and parsed, but not run.
# These checks are heuristics: they catch a wrong, broken or crudely modified
# script, but they cannot prove that a script is harmless.
cmai_script_findings() {
  local file="$1"
  local option entry line host

  head -n 1 "${file}" | grep -qE '^#!(/usr)?/bin/(env )?bash' || echo "is not a bash script"
  bash -n "${file}" 2>/dev/null || echo "has a syntax error"
  for option in "${CMAI_REQUIRED_OPTIONS[@]}"; do
    grep -qF -e "${option})" "${file}" || echo "lacks the option ${option}"
  done
  [ "$(wc -c < "${file}")" -le 200000 ] || echo "is larger than expected"
  if LC_ALL=C grep -qE '.{1000}' "${file}"; then
    echo "has very long lines"
  fi
  line="$(LC_ALL=C grep -n -m 1 '[^[:print:][:space:]]' "${file}" | cut -d: -f1 || true)"
  if [ -n "${line}" ]; then
    echo "contains non-ASCII or control characters (line ${line})"
  fi
  for entry in "${CMAI_UNEXPECTED_PATTERNS[@]}"; do
    line="$(LC_ALL=C grep -nE -m 1 -e "${entry#*|}" "${file}" | cut -d: -f1 || true)"
    if [ -n "${line}" ]; then
      echo "${entry%%|*} (line ${line})"
    fi
  done
  while IFS= read -r host; do
    case "${CMAI_KNOWN_HOSTS}" in
      *" ${host} "*) ;;
      *) echo "names the unknown host ${host}" ;;
    esac
  done < <(LC_ALL=C grep -oE 'https?://[^/"'"'"' )]+' "${file}" | sed 's|.*://||; s|:.*||' | sort -u)
  return 0
}

# Writes a cmai setting. The file is private from the moment it is created.
write_cmai_setting() {
  local file="${CMAI_CONFIG_DIR}/$1"
  (
    umask 077
    mkdir -p "${CMAI_CONFIG_DIR}" && printf '%s\n' "$2" > "${file}"
  ) && chmod 700 "${CMAI_CONFIG_DIR}" && chmod 600 "${file}"
}

# Prints the editor command that git starts for a commit message.
detect_editor() {
  local editor
  editor="$(git var GIT_EDITOR 2>/dev/null || true)"
  if [ -z "${editor}" ]; then
    editor="${VISUAL:-${EDITOR:-}}"
  fi
  printf '%s' "${editor}"
}

# Prints vim, nvim or other for an editor command. Follows symbolic links such
# as the Debian `editor` alternative.
editor_kind() {
  local command_name="${1%% *}"
  local resolved
  resolved="$(command -v -- "${command_name}" 2>/dev/null || true)"
  if [ -n "${resolved}" ]; then
    resolved="$(readlink -f -- "${resolved}" 2>/dev/null || printf '%s' "${resolved}")"
  fi
  case "$(basename -- "${resolved:-${command_name}}")" in
    nvim*) echo nvim ;;
    vim*|gvim*|vi|view) echo vim ;;
    *) echo other ;;
  esac
}

# Prints the config file that Vim or Neovim loads at startup. Fails for Neovim
# with init.lua, because init.lua cannot take the Vim script snippet as it is.
editor_config_path() {
  local config_home="${XDG_CONFIG_HOME:-${HOME}/.config}"
  local candidate
  if [ "$1" = nvim ]; then
    [ ! -f "${config_home}/nvim/init.lua" ] || return 1
    printf '%s\n' "${config_home}/nvim/init.vim"
    return 0
  fi
  # Vim loads only the first vimrc that exists, so a new ~/.vimrc would hide
  # an existing vimrc at one of the other locations.
  for candidate in "${HOME}/.vimrc" "${HOME}/.vim/vimrc" "${config_home}/vim/vimrc"; do
    if [ -f "${candidate}" ]; then
      printf '%s\n' "${candidate}"
      return 0
    fi
  done
  printf '%s\n' "${HOME}/.vimrc"
}

