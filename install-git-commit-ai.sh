#!/usr/bin/env bash
#
# Sets up AI-generated git commit messages with mittwald AI: installs cmai,
# configures it and installs a prepare-commit-msg hook into the git template
# directory.
#
# Everything runs from main() on the last line, so that a partially downloaded
# script (curl | bash) does nothing.

set -euo pipefail

# cmai is third-party code. The installer downloads the latest version, checks
# the script for unexpected content (see cmai_script_findings) and installs the
# script itself. No downloaded code runs during the installation.
CMAI_REPO='https://github.com/mrgoonie/cmai.git'
CMAI_INSTALL_DIR="${HOME}/git-commit-ai"
CMAI_LINK='/usr/local/bin/cmai'
# Options that this installer and the hook need. Older cmai versions lack them.
CMAI_REQUIRED_OPTIONS=(--message-only --print-config --use-custom --clear-model-options --max-output-tokens --extra-body)
CMAI_CONFIG_DIR="${HOME}/.config/git-commit-ai"

# Hosts that the cmai script names today. Another host is a finding.
CMAI_KNOWN_HOSTS=' openrouter.ai localhost 127.0.0.1 github.com my-api.com '
# Constructs that cmai has no need for, as "description|extended regex".
WORD_START='(^|[^[:alnum:]_.-])'
WORD_END='([^[:alnum:]_-]|$)'
CMAI_UNEXPECTED_PATTERNS=(
  "runs generated code (eval)|${WORD_START}eval${WORD_END}"
  "decodes hidden data|${WORD_START}(base64|xxd|uudecode|openssl)${WORD_END}"
  "opens a raw network connection|/dev/(tcp|udp)/"
  "starts a tool that cmai does not need|${WORD_START}(sudo|wget|nc|ncat|netcat|socat|ssh|scp|sftp|telnet|python[0-9.]*|perl|ruby|php|crontab|nohup|setsid|disown|chattr|mkfifo)${WORD_END}"
  "pipes data into a shell|\\|[[:space:]]*(ba|z|da)?sh${WORD_END}"
  "runs a command string in a shell|${WORD_START}(ba|z|da)?sh[[:space:]]+-c${WORD_END}"
  "loads another script|${WORD_START}source[[:space:]]"
  "names a sensitive file|\\.ssh|authorized_keys|\\.gnupg|\\.aws|\\.netrc|\\.git-credentials|_history|\\.bashrc|\\.bash_profile|\\.profile|\\.zshrc|/etc/(passwd|shadow)|/proc/"
  "changes the git configuration|${WORD_START}git[[:space:]]+(config|remote)${WORD_END}|credential"
  "deletes directories|${WORD_START}rm[[:space:]]+-[[:alpha:]]*[rR]"
  "contains encoded text|\\\\x[0-9a-fA-F]{2}|\\\\[0-7]{3}"
  "starts a background process|[^&]&[[:space:]]*\$"
)

AI_BASE_URL='https://llm.aihosting.mittwald.de/v1'
AI_MODEL='Qwen3.8-27B-NVFP4'
AI_MAX_OUTPUT_TOKENS=32768
AI_EXTRA_BODY='{"chat_template_kwargs":{"enable_thinking":false}}'

# Text that every version of the hook written by this installer contains.
HOOK_SIGNATURE='cmai --message-only'

hook_content() {
  cat <<'HOOK_EOF'
#!/usr/bin/env bash
#
# prepare-commit-msg hook: puts a commit message generated by cmai at the top
# of the message that git opens in the editor.
# Installed by install-git-commit-ai.sh (https://github.com/mittwald/ai-developer-tools).
#
# The hook never blocks a commit. If the generation fails, the hook reports the
# reason and git opens the editor without a generated message.

MSG_FILE="${1:-}"
SOURCE="${2:-}"   # empty for a plain `git commit`; else message, template, merge, squash or commit

MAX_ATTEMPTS=3
TIMEOUT_SECONDS=30            # limit of the first attempt
TIMEOUT_INCREASE_PERCENT=50   # growth of the limit after each timeout: 30s, 45s, 68s
KILL_AFTER_SECONDS=2

case "${SOURCE}" in
  message|merge|squash|template|commit) exit 0 ;;
esac
[ -n "${MSG_FILE}" ] || exit 0

# Status texts, shown as "1/3 <text>...". ASCII only, no line longer than 72.
MESSAGES=(
  'Asking the diff what it did this time'
  'Translating your changes into human'
  'Teaching the model to say "fix" politely'
  'Squinting at your staged changes'
  'Pretending this was the plan all along'
  'Turning chaos into Conventional Commits'
  'Finding a nicer word for "oops"'
  'Counting the files you swear you never touched'
  'Blaming the previous commit'
  'Resisting the urge to write "misc changes"'
  'Consulting the commit message oracle'
  'Reading your diff so the reviewers can skim it'
  'Making "wip" sound professional'
  'Flipping a coin between feat and fix'
  'Brewing a fresh subject line'
  'Squeezing three hours into seventy characters'
  'Looking for the why behind the what'
  'Polishing the imperative mood'
  'Negotiating with the linter in advance'
  'Hiding the evidence of trial and error'
  'Asking the GPUs for their honest opinion'
  'Convincing the model that the tabs were intended'
  'Composing a haiku, then deleting it'
  'Removing "finally works" from the draft'
  'Inventing a scope that sounds official'
  'Giving your typo fix the gravitas it deserves'
  'Checking whether this counts as a refactor'
  'Skipping the part where it says "stuff"'
  'Writing history, one line at a time'
  'Explaining it to your future self'
  'Dressing up the diff for code review'
  'Rounding "quick fix" up to "improvement"'
  'Decoding what "temp2_final" was supposed to mean'
  'Warming up the tokens'
  'Deciding this is definitely not a breaking change'
  'Searching for a verb that is not "update"'
  'Reticulating commit splines'
  'Fitting an epic into the subject line'
  'Taking credit for what the compiler made you do'
  'Preparing your alibi for git blame'
  'Asking mittwald AI very nicely'
  'Thinking in German, answering in English'
  'Making the changelog proud'
  'Distilling your diff into one honest sentence'
  'Arguing with itself about the scope'
  'Promising the reviewers it is a small change'
  'Steering clear of "various improvements"'
  'Reading between the hunks'
  'Editing the swear words out of the summary'
  'Trusting that the tests passed'
)
MESSAGE_FRAMES=30   # frames until the next text, about 3 seconds

# On a terminal, the status is one line that is rewritten in place.
if [ -t 2 ] && [ "${TERM:-dumb}" != "dumb" ]; then
  LIVE=1
else
  LIVE=0
fi
if [ "${LIVE}" -eq 1 ] && [ -z "${NO_COLOR:-}" ]; then
  COLOR=1
  C_DIM=$'\033[2m'
  C_RED=$'\033[31m'
  C_RESET=$'\033[0m'
else
  COLOR=0
  C_DIM=''
  C_RED=''
  C_RESET=''
fi

# Colors of the status text (24-bit): mittwald blue, purple, salmon and rose.
# The colors flow through the letters. The part of the text that shows the
# elapsed share of the time limit is bold and in full color, the rest is muted.
# The attempt counter in front of the text stays dim, in the color of the theme.
GRADIENT_STOPS=(75 56 232  155 110 216  231 160 134  182 117 133)
GRADIENT_SIZE=60    # color steps of one cycle through all stops
MUTED_GRAY=125      # the muted colors are a mix with this gray
MUTED_PERCENT=62
BRIGHT=()
MUTED=()

# Fills BRIGHT and MUTED with one escape sequence per color step.
build_gradient() {
  local stops=$(( ${#GRADIENT_STOPS[@]} / 3 ))
  local step segment from to position ease channel value bright muted
  for ((step = 0; step < GRADIENT_SIZE; step++)); do
    segment=$(( step * stops / GRADIENT_SIZE ))
    from=$(( segment * 3 ))
    to=$(( (from + 3) % ${#GRADIENT_STOPS[@]} ))
    position=$(( step * stops % GRADIENT_SIZE * 1000 / GRADIENT_SIZE ))
    ease=$(( position * position * (3000 - 2 * position) / 1000000 ))
    bright=''
    muted=''
    for channel in 0 1 2; do
      value=$(( GRADIENT_STOPS[from + channel] + (GRADIENT_STOPS[to + channel] - GRADIENT_STOPS[from + channel]) * ease / 1000 ))
      bright+=";${value}"
      muted+=";$(( value + (MUTED_GRAY - value) * MUTED_PERCENT / 100 ))"
    done
    BRIGHT[step]=$'\033'"[0;1;38;2${bright}m"
    MUTED[step]=$'\033'"[0;38;2${muted}m"
  done
}

# Draws the status line. $1 = attempt counter, $2 = text, $3 = frame number,
# $4 = number of text characters in full color.
draw() {
  local text="$2"
  local length=${#2}
  local line=''
  local i step
  if [ "${COLOR}" -eq 1 ]; then
    line="${C_DIM}$1 "
    for ((i = 0; i < length; i++)); do
      step=$(( (i * GRADIENT_SIZE / length + GRADIENT_SIZE - $3 * 2 % GRADIENT_SIZE) % GRADIENT_SIZE ))
      if [ "${i}" -lt "$4" ]; then
        line+="${BRIGHT[step]}${text:i:1}"
      else
        line+="${MUTED[step]}${text:i:1}"
      fi
    done
    line+="${C_RESET}"
  else
    line="$1 ${text}"
  fi
  printf '\r%s\033[K' "${line}" >&2
}

# Redraws the status line until the hook stops this loop.
animate() {
  local frame=0
  local text=''
  local full=0
  while :; do
    if [ $((frame % MESSAGE_FRAMES)) -eq 0 ]; then
      text="${MESSAGES[(message_start + frame / MESSAGE_FRAMES * 7) % ${#MESSAGES[@]}]}..."
    fi
    if [ -n "${TIMEOUT_BIN}" ]; then
      full=$(( (SECONDS - started) * ${#text} / TIMEOUT_SECONDS ))
    else
      full=${#text}
    fi
    draw "${attempts}/${MAX_ATTEMPTS}" "${text}" "${frame}" "${full}"
    frame=$((frame + 1))
    sleep 0.1 2>/dev/null || sleep 1
  done
}

# Replaces the status line with a final line. $1 = color, $2 = text.
finish() {
  if [ "${LIVE}" -eq 1 ]; then
    printf '\r\033[K' >&2
  fi
  printf '%s%s%s\n' "$1" "$2" "${C_RESET}" >&2
}

# Prints the last lines of cmai output. Control characters are removed, so that
# text from the API cannot send escape sequences to the terminal.
cmai_output() {
  local file
  for file in "${ERR_FILE}" "${OUT_FILE}"; do
    [ -s "${file}" ] || continue
    LC_ALL=C tr -d '\000-\010\013-\037\177' < "${file}" |
      grep -v '^[[:space:]]*$' | tail -n 3 | cut -c 1-300 | sed 's/^/  /'
    return
  done
}

# Reports why there is no generated message. $1 = reason, $2 = "details" to add
# the cmai output.
fail() {
  finish "${C_RED}" "No commit message generated: $1"
  if [ "${2:-}" = details ]; then
    cmai_output >&2
  fi
  exit 0
}

command -v cmai >/dev/null 2>&1 || fail "cmai not found in PATH"

if command -v timeout >/dev/null 2>&1; then
  TIMEOUT_BIN=timeout
elif command -v gtimeout >/dev/null 2>&1; then
  TIMEOUT_BIN=gtimeout
else
  TIMEOUT_BIN=''
fi

WORK_DIR="$(mktemp -d 2>/dev/null)" || fail "mktemp failed"
OUT_FILE="${WORK_DIR}/out"
ERR_FILE="${WORK_DIR}/err"
child=''
ticker=''

# Runs from the EXIT trap.
# shellcheck disable=SC2329
cleanup() {
  [ -n "${ticker}" ] && kill "${ticker}" 2>/dev/null
  [ -n "${child}" ] && kill "${child}" 2>/dev/null
  rm -f "${OUT_FILE}" "${ERR_FILE}"
  rmdir "${WORK_DIR}" 2>/dev/null
}
trap cleanup EXIT
# timeout runs cmai in its own process group, so Ctrl-C does not reach cmai.
# The hook exits instead, and cleanup stops cmai.
trap '[ "${LIVE}" -eq 1 ] && printf "%s\n" "${C_RESET}" >&2; exit 130' INT
trap 'exit 143' TERM HUP

if [ "${COLOR}" -eq 1 ]; then
  build_gradient
fi

attempts=0
exitcode=0
while [ "${attempts}" -lt "${MAX_ATTEMPTS}" ]; do
  attempts=$((attempts + 1))
  message_start=$((RANDOM % ${#MESSAGES[@]}))
  started="${SECONDS}"
  if [ -n "${TIMEOUT_BIN}" ]; then
    "${TIMEOUT_BIN}" -k "${KILL_AFTER_SECONDS}" "${TIMEOUT_SECONDS}" \
      cmai --message-only > "${OUT_FILE}" 2> "${ERR_FILE}" &
  else
    cmai --message-only > "${OUT_FILE}" 2> "${ERR_FILE}" &
  fi
  child=$!
  if [ "${LIVE}" -eq 1 ]; then
    animate &
    ticker=$!
  else
    printf '%s/%s %s...\n' "${attempts}" "${MAX_ATTEMPTS}" "${MESSAGES[message_start]}" >&2
  fi
  wait "${child}"; exitcode=$?
  child=''
  if [ -n "${ticker}" ]; then
    kill "${ticker}" 2>/dev/null
    wait "${ticker}" 2>/dev/null
    ticker=''
  fi

  # timeout exits with 124 after SIGTERM and with 137 after SIGKILL.
  if [ "${exitcode}" -ne 124 ] && [ "${exitcode}" -ne 137 ]; then
    break
  fi
  if [ "${attempts}" -ge "${MAX_ATTEMPTS}" ]; then
    fail "cmai timed out after ${TIMEOUT_SECONDS}s (attempt ${attempts}/${MAX_ATTEMPTS})" details
  fi
  [ "${LIVE}" -eq 1 ] || printf 'Timed out after %ss\n' "${TIMEOUT_SECONDS}" >&2
  TIMEOUT_SECONDS=$((TIMEOUT_SECONDS + (TIMEOUT_SECONDS * TIMEOUT_INCREASE_PERCENT + 99) / 100))
done

[ "${exitcode}" -eq 0 ] || fail "cmai failed (exit ${exitcode})" details
COMMIT_MSG="$(cat "${OUT_FILE}")"
[ -n "${COMMIT_MSG}" ] || fail "cmai returned an empty message" details

if { printf '%s\n' "${COMMIT_MSG}"; cat "${MSG_FILE}"; } > "${MSG_FILE}.tmp" &&
  mv "${MSG_FILE}.tmp" "${MSG_FILE}"; then
  finish "${C_DIM}" "Generated commit message (${SECONDS}s)"
else
  rm -f "${MSG_FILE}.tmp"
  fail "could not write ${MSG_FILE}"
fi
exit 0
HOOK_EOF
}

