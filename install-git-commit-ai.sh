# Asks a yes/no question. $1 = question, $2 = default answer (y or n).
ask() {
  local question="$1"
  local default="$2"
  local hint='[y/N]'
  local answer=''
  if [ "${default}" = y ]; then
    hint='[Y/n]'
  fi
  printf '  %s%s %s:%s ' "${C_BOLD}${C_BLUE}" "${question}" "${hint}" "${C_RESET}"
  if is_interactive; then
    read -r answer < /dev/tty || true
  elif [ "${default}" = y ]; then
    echo 'Y'
  else
    echo 'N'
  fi
  if [ -z "${answer}" ]; then
    answer="${default}"
  fi
  case "${answer}" in
    y|Y|yes|Yes|YES) return 0 ;;
    *) return 1 ;;
  esac
}

prompt_step() {
  heading "$1" "$2"
  echo
  ask "Run this step?" y
}

# Reads the API key without echo, so that the key does not stay on the screen
# or in the terminal scrollback.
prompt_api_key() {
  printf '  %s%s:%s ' "${C_BOLD}${C_BLUE}" "$1" "${C_RESET}"
  cmai_api_key=''
  if is_interactive; then
    read -r -s cmai_api_key < /dev/tty || true
  fi
  echo
}

# The tilde in the next two functions is literal text, as git config stores it.
# shellcheck disable=SC2088
to_tilde_path() {
  local p="$1"
  if [ "$p" = "$HOME" ]; then
    printf '~'
  elif [ "${p#"$HOME"/}" != "$p" ]; then
    printf '~/%s' "${p#"$HOME"/}"
  else
    printf '%s' "$p"
  fi
}

# shellcheck disable=SC2088
resolve_template_dir() {
  local p="$1"
  case "$p" in
    "~") printf '%s\n' "${HOME}" ;;
    "~/"*) printf '%s/%s\n' "${HOME}" "${p#"~/"}" ;;
    *) printf '%s\n' "$p" ;;
  esac
}

# True for /dir and for C:/dir, the form in which git for Windows stores paths.
is_absolute_path() {
  case "$1" in
    /*|[A-Za-z]:[/\\]*) return 0 ;;
    *) return 1 ;;
  esac
}

prompt_template_dir() {
  local initial="$1"
  local input=''
  local resolved=''

  while true; do
    if is_interactive && [ "${BASH_VERSINFO[0]}" -ge 4 ]; then
      printf '  %sTemplate directory:%s ' "${C_BOLD}${C_BLUE}" "${C_RESET}"
      read -r -e -i "${initial}" input < /dev/tty || true
    elif is_interactive; then
      # bash 3.2 (macOS) cannot put the default into the input line.
      printf '  %sTemplate directory [%s]:%s ' "${C_BOLD}${C_BLUE}" "${initial}" "${C_RESET}"
      read -r input < /dev/tty || true
    else
      printf '  %sTemplate directory:%s %s\n' "${C_BOLD}${C_BLUE}" "${C_RESET}" "$(code "${initial}")"
      input="${initial}"
    fi

    [ -z "${input}" ] && input="${initial}"
    resolved="$(resolve_template_dir "${input}")"
    if ! is_absolute_path "${resolved}"; then
      error "template directory must be an absolute path."
      if is_interactive; then
        continue
      fi
      return 1
    fi

    template_dir="${resolved}"
    return 0
  done
}

