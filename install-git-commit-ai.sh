# Downloads the latest cmai into a temporary directory and checks the script.
# Sets downloaded_script. Fails if the user does not accept a script with
# unexpected content.
# Downloads the latest cmai into a temporary directory and sets
# downloaded_script. Returns 1 if the download fails.
fetch_cmai() {
  local src_dir

  if ! command -v mktemp >/dev/null 2>&1; then
    error "mktemp is required to install $(code "cmai")."
    echo "  ${C_RED}Please install $(code "cmai")${C_RED} manually first. Aborting.${C_RESET}" >&2
    exit 1
  fi
  tmp_dir="$(mktemp -d)"
  src_dir="${tmp_dir}/cmai"
  downloaded_script="${src_dir}/git-commit.sh"

  action "$(code "git clone --depth 1 ${CMAI_REPO} ${src_dir}")"
  if ! git clone --quiet --depth 1 --template= "${CMAI_REPO}" "${src_dir}" < /dev/null 2>&1 | dim_output ||
    [ ! -f "${downloaded_script}" ]; then
    return 1
  fi
}

# Checks the downloaded cmai and shows what the check found. Returns 1 if the
# script has unexpected content.
check_downloaded_cmai() {
  local findings finding commit

  commit="$(git -C "$(dirname "${downloaded_script}")" log -1 --format='%h from %cd' --date=short 2>/dev/null || true)"
  action "Checking $(code "git-commit.sh") (commit ${commit:-unknown}) for unexpected content"
  findings="$(cmai_script_findings "${downloaded_script}")"
  if [ -z "${findings}" ]; then
    echo "    ${C_DIM}Nothing unexpected found.${C_RESET}"
    return 0
  fi
  echo
  warning "the downloaded $(code "cmai")${C_YELLOW} script does not look as expected. The script:"
  while IFS= read -r finding; do
    echo "    ${C_YELLOW}- ${finding}${C_RESET}"
  done <<< "${findings}"
  echo "  ${C_YELLOW}Review ${CMAI_REPO%.git} before you continue.${C_RESET}"
  echo
  return 1
}

download_cmai() {
  if ! fetch_cmai; then
    die "failed to download $(code "cmai"). Please install it manually first and re-run this script. Aborting."
  fi
  check_downloaded_cmai || ask "Install this script anyway?" n
}

remove_download() {
  action "Removing $(code "${tmp_dir}")"
  rm -rf "${tmp_dir}"
  tmp_dir=''
}

# Installs the downloaded script with the layout of the cmai install script: a
# copy in the home directory and the cmai command in a directory on the PATH.
install_downloaded_cmai() {
  local target="${CMAI_INSTALL_DIR}/git-commit.sh"

  action "$(code "mkdir -p ${CMAI_INSTALL_DIR}")"
  action "$(code "cp ${downloaded_script} ${target}")"
  if ! mkdir -p "${CMAI_INSTALL_DIR}" || ! cp "${downloaded_script}" "${target}" || ! chmod +x "${target}"; then
    die "failed to copy $(code "cmai") to $(code "${CMAI_INSTALL_DIR}"). Aborting."
  fi
  if ! link_cmai "${target}"; then
    warning "could not put $(code "cmai")${C_YELLOW} on the PATH. The hook works without it."
    echo "  ${C_YELLOW}To run cmai yourself, use${C_RESET} $(code "$(to_tilde_path "${target}")")${C_YELLOW}.${C_RESET}"
  fi
  remove_download

  if ! cmai_is_current; then
    error "failed to install $(code "cmai")."
    if command -v cmai >/dev/null 2>&1; then
      echo "  ${C_RED}$(command -v cmai) comes first on the PATH and is an older version.${C_RESET}" >&2
    fi
    echo "  ${C_RED}Please fix this and re-run this script. Aborting.${C_RESET}" >&2
    exit 1
  fi
  echo "  ${C_GREEN}Done.${C_RESET}"
}

step_install_cmai() {
  local title

  if cmai_is_current; then
    heading 1 "Install $(code "cmai")"
    echo
    echo "  $(code "cmai") ${C_GREEN}is already installed.${C_RESET}"
    update_installed_cmai
    update_cmai_for_keychain
    return 0
  fi

  if find_cmai >/dev/null 2>&1; then
    title="Update $(code "cmai") (the installed version lacks options that this setup needs)"
  else
    title="Install $(code "cmai")"
  fi
  if ! prompt_step 1 "${title}"; then
    abort
  fi
  if ! download_cmai; then
    echo "  ${C_RED}$(code "cmai")${C_RED} was not installed. Aborting.${C_RESET}"
    exit 1
  fi
  install_downloaded_cmai
}

# Updates a cmai that this installer (or the install script of cmai) installed
# to the latest version, if the latest version differs and the content check
# finds nothing. cmai has no version number, so a different script counts as a
# newer one. A cmai from another source stays as it is. A failed download keeps
# the installed cmai.
update_installed_cmai() {
  local installed="${CMAI_INSTALL_DIR}/git-commit.sh"

  if [ ! -f "${installed}" ] || ! cmp -s "${cmai_path}" "${installed}"; then
    echo "  ${C_DIM}$(code "${cmai_path}")${C_DIM} is not from this installer and is not updated.${C_RESET}"
    return 0
  fi
  echo
  echo "  Looking for a newer $(code "cmai")."
  if ! fetch_cmai; then
    warning "failed to download $(code "cmai")${C_YELLOW}. Keeping the installed cmai."
    remove_download
    return 0
  fi
  if cmp -s "${downloaded_script}" "${installed}"; then
    cmai_is_latest=1
    echo "  $(code "cmai") ${C_GREEN}is the latest version.${C_RESET}"
    remove_download
    return 0
  fi
  echo "  A newer $(code "cmai") is available."
  if ! check_downloaded_cmai; then
    echo "  ${C_YELLOW}Keeping the installed cmai.${C_RESET}"
    remove_download
    return 0
  fi
  if ! ask "Update cmai?" y; then
    echo "  ${C_YELLOW}Keeping the installed cmai.${C_RESET}"
    remove_download
    return 0
  fi
  install_downloaded_cmai
  cmai_is_latest=1
}

# The system keychain can keep the API key only if cmai takes the key from the
# environment. If the installed cmai cannot do that, a newer one may.
update_cmai_for_keychain() {
  if cmai_reads_key_from_environment "${cmai_path}" || ! keychain_exists; then
    return 0
  fi
  echo
  echo "  The installed cmai cannot take the API key from the $(keychain_title)."
  if [ "${cmai_is_latest}" -eq 1 ]; then
    echo "  ${C_YELLOW}The latest cmai cannot do this either. The API key stays in a file that only you can read.${C_RESET}"
    return 0
  fi
  if ! ask "Look for a newer cmai?" y; then
    return 0
  fi
  if ! download_cmai; then
    echo "  ${C_YELLOW}Keeping the installed cmai.${C_RESET}"
    remove_download
  elif cmai_reads_key_from_environment "${downloaded_script}"; then
    install_downloaded_cmai
  else
    echo "  ${C_YELLOW}The latest cmai cannot do this either. The API key stays in a file that only you can read.${C_RESET}"
    remove_download
  fi
}

# Prints the directory that gets the cmai command.
cmai_bin_dir() {
  if [ -n "${CMAI_BIN_DIR:-}" ]; then
    printf '%s\n' "${CMAI_BIN_DIR}"
  elif [ "${PLATFORM}" = windows ]; then
    # Git Bash has ~/bin on its PATH.
    printf '%s\n' "${HOME}/bin"
  else
    printf '%s\n' '/usr/local/bin'
  fi
}

# Puts cmai on the PATH. $1 = installed script. Needs sudo only if the
# directory is not writable.
link_cmai() {
  local target="$1"
  local bin_dir link
  bin_dir="$(cmai_bin_dir)"
  link="${bin_dir}/cmai"

  if [ "${link}" -ef "${target}" ]; then
    echo "    ${C_DIM}${link} already points to ${target}.${C_RESET}"
  elif [ "${PLATFORM}" = windows ]; then
    # Git Bash needs special rights for a symbolic link, so the command is a copy.
    action "$(code "cp ${target} ${link}")"
    mkdir -p "${bin_dir}" && cp "${target}" "${link}"
  elif mkdir -p "${bin_dir}" 2>/dev/null && [ -w "${bin_dir}" ]; then
    action "$(code "ln -sf ${target} ${link}")"
    ln -sf "${target}" "${link}"
  elif command -v sudo >/dev/null 2>&1; then
    if [ ! -d "${bin_dir}" ]; then
      action "$(code "sudo mkdir -p ${bin_dir}")"
      sudo mkdir -p "${bin_dir}" < /dev/null || return 1
    fi
    action "$(code "sudo ln -sf ${target} ${link}")"
    sudo ln -sf "${target}" "${link}" < /dev/null
  else
    error "$(code "${bin_dir}") is not writable and $(code "sudo") was not found."
    return 1
  fi
}

step_api_key() {
  local prompt='API key (optional, input is hidden)'

  heading 2 "Configure API key for $(code "cmai")"
  echo
  if [ -s "${CMAI_CONFIG_DIR}/config" ] || [ -s "${KEYCHAIN_FILE}" ]; then
    echo "  ${C_GREEN}An API key is already stored.${C_RESET}"
    prompt='New API key (empty keeps the stored key, input is hidden)'
  fi
  if [ -n "${MITTWALD_AI_API_KEY:-}" ]; then
    echo "  ${C_GREEN}Found key in${C_RESET} $(code "MITTWALD_AI_API_KEY")${C_GREEN}.${C_RESET}"
    if ask "Use key from MITTWALD_AI_API_KEY" y; then
      cmai_api_key="${MITTWALD_AI_API_KEY}"
    else
      prompt_api_key "${prompt}"
    fi
  else
    prompt_api_key "${prompt}"
  fi
  # A pasted key can carry spaces or a line end.
  cmai_api_key="${cmai_api_key//[[:space:]]/}"
}

# Stores the API key from step 2. The key goes into the system keychain where
# that is possible, and a key that is in the key file of cmai moves there too.
# Otherwise the key is in the key file, which only the user can read.
store_api_key() {
  local key="${cmai_api_key}"
  local key_file="${CMAI_CONFIG_DIR}/config"
  local question
  local can_use_keychain=0

  question="Store the API key in the $(keychain_title)?"
  if cmai_reads_key_from_environment "${cmai_path}" && keychain_exists; then
    can_use_keychain=1
    if [ -z "${key}" ] && [ -s "${key_file}" ]; then
      key="$(cat "${key_file}")"
      question="Move the stored API key into the $(keychain_title)?"
    fi
  elif [ -z "${key}" ] && [ -s "${KEYCHAIN_FILE}" ]; then
    # The key is in the keychain, but this cmai cannot take it from there.
    key="$(keychain_get || true)"
    cmai_api_key="${key}"
  fi

  if [ -z "${key}" ]; then
    if [ -s "${KEYCHAIN_FILE}" ]; then
      keychain_api_key="$(keychain_get || true)"
      echo "  ${C_GREEN}Keeping the API key in the $(keychain_title).${C_RESET}"
    elif [ -s "${key_file}" ]; then
      echo "  ${C_GREEN}Keeping the stored API key.${C_RESET}"
    else
      echo "  ${C_YELLOW}No API key set. Re-run this installer to store a key later.${C_RESET}"
    fi
    return 0
  fi

  if [ "${can_use_keychain}" -eq 1 ] && ask "${question}" y; then
    action "Storing API key in the $(keychain_title)"
    if keychain_set "${key}" && [ "$(keychain_get || true)" = "${key}" ]; then
      if ! write_cmai_setting keychain "${KEYCHAIN_ENTRY}"; then
        die "failed to write $(code "${KEYCHAIN_FILE}"). Aborting."
      fi
      if [ -e "${key_file}" ]; then
        action "Removing $(code "$(to_tilde_path "${key_file}")")"
        rm -f "${key_file}"
      fi
      keychain_api_key="${key}"
      return 0
    fi
    warning "could not store the API key in the $(keychain_title). The key goes into a file."
  fi

  if [ -n "${cmai_api_key}" ]; then
    action "Writing API key to $(code "$(to_tilde_path "${key_file}")") (only you can read this file)"
    if ! write_cmai_setting config "${key}"; then
      die "failed to store the API key. Aborting."
    fi
  else
    echo "  ${C_GREEN}Keeping the stored API key.${C_RESET}"
  fi
  if [ -e "${KEYCHAIN_FILE}" ]; then
    keychain_delete || true
    rm -f "${KEYCHAIN_FILE}"
  fi
}

step_configure_cmai() {
  local preview_cmd
  local cmai_cmd=("${cmai_path}" --clear-model-options
                  --use-custom "${AI_BASE_URL}"
                  --model "${AI_MODEL}"
                  --temperature 0.7
                  --top-p 0.8
                  --presence-penalty 1.5
                  --max-output-tokens "${AI_MAX_OUTPUT_TOKENS}"
                  --extra-body "${AI_EXTRA_BODY}"
                  --print-config)

  if ! prompt_step 3 "Configure $(code "cmai") to use mittwald AI"; then
    abort
  fi

  store_api_key

  preview_cmd="cmai --clear-model-options
         --use-custom \"${AI_BASE_URL}\"
         --model      \"${AI_MODEL}\"
         --temperature 0.7
         --top-p 0.8
         --presence-penalty 1.5
         --max-output-tokens ${AI_MAX_OUTPUT_TOKENS}
         --extra-body '${AI_EXTRA_BODY}'
         --print-config"
  action "$(code "${preview_cmd}")"
  # With the key from the keychain in the environment, cmai reports the key as set.
  if ! CMAI_API_KEY="${keychain_api_key}" "${cmai_cmd[@]}" < /dev/null 2>&1 | dim_output; then
    die "failed to configure $(code "cmai"). Aborting."
  fi
  # cmai exits on --print-config before persisting --max-output-tokens, so save it directly.
  if ! write_cmai_setting max_output_tokens "${AI_MAX_OUTPUT_TOKENS}"; then
    die "failed to store the output token limit. Aborting."
  fi
  echo "  ${C_GREEN}Done.${C_RESET}"
}

step_template_dir() {
  local existing_dir resolved_existing_dir hooks_path

  existing_dir="$(git config --global --get init.templatedir || true)"
  heading 4 "Configure template directory"
  echo
  if [ -n "${existing_dir}" ]; then
    resolved_existing_dir="$(resolve_template_dir "${existing_dir}")"
    printf '  %sTemplate directory:%s %s\n' "${C_BOLD}" "${C_RESET}" "$(code "${existing_dir}")"
    if ask "Use configured directory" y; then
      if ! is_absolute_path "${resolved_existing_dir}"; then
        error "configured template directory must be an absolute path."
        if ! prompt_template_dir "${HOME}/.git-templates"; then
          abort
        fi
        warn_template_dir_not_global
      else
        template_dir="${resolved_existing_dir}"
      fi
    else
      if ! prompt_template_dir "${existing_dir}"; then
        abort
      fi
      if [ "${template_dir}" != "${resolved_existing_dir}" ]; then
        warn_template_dir_not_global
      fi
    fi
  else
    if ! prompt_template_dir "${HOME}/.git-templates"; then
      abort
    fi
    action "Creating $(code "${template_dir}")"
    if ! mkdir -p "${template_dir}"; then
      die "failed to create $(code "${template_dir}"). Aborting."
    fi
    # The form ~/dir is the same on every system, also for git on Windows.
    action "$(code "git config --global init.templatedir '$(to_tilde_path "${template_dir}")'")"
    git config --global init.templatedir "$(to_tilde_path "${template_dir}")"
  fi

  hooks_path="$(git config --global --get core.hooksPath || git config --system --get core.hooksPath || true)"
  if [ -n "${hooks_path}" ]; then
    echo
    warning "$(code "core.hooksPath")${C_YELLOW} is set to $(code "${hooks_path}")${C_YELLOW}."
    echo "  ${C_YELLOW}Git then ignores the hooks of a repository, so the hook from the template will not run.${C_RESET}"
  fi
}

# True if the hooks are links to HOOK_SOURCE. Windows has no symbolic links
# without extra rights, so there the template and each repository keep a copy.
links_hooks() {
  [ "${PLATFORM}" != windows ]
}

# True if $1 is a link to HOOK_SOURCE.
is_hook_link() {
  [ -L "$1" ] && [ "$(readlink "$1")" = "${HOOK_SOURCE}" ]
}

# True if $1 is a hook from this installer, also an older one.
is_installer_hook() {
  grep -qF -e "${HOOK_SIGNATURE}" -e "${HOOK_SIGNATURE_OLD}" "$1" 2>/dev/null
}

# True if the hook $1 needs no change.
hook_is_current() {
  if links_hooks; then
    is_hook_link "$1" && [ "$(cat "${HOOK_SOURCE}" 2>/dev/null)" = "$(hook_content)" ]
  else
    [ ! -L "$1" ] && [ "$(cat "$1" 2>/dev/null)" = "$(hook_content)" ]
  fi
}

# Writes HOOK_SOURCE. A commit that runs the hook meanwhile reads the old or
# the new file, never a partly written one.
write_hook_source() {
  local tmp_hook="${HOOK_SOURCE}.tmp.$$"
  action "Writing $(code "$(to_tilde_path "${HOOK_SOURCE}")")"
  if mkdir -p "${CMAI_INSTALL_DIR}" &&
    hook_content > "${tmp_hook}" &&
    chmod +x "${tmp_hook}" &&
    mv -f "${tmp_hook}" "${HOOK_SOURCE}"; then
    return 0
  fi
  rm -f "${tmp_hook}"
  return 1
}

# Puts the hook at $1: a link to HOOK_SOURCE, or on Windows a copy.
# $2 = quiet: do not show the action.
place_hook() {
  local target="$1"
  local quiet="${2:-}"
  if links_hooks; then
    [ -n "${quiet}" ] || action "$(code "ln -sf $(to_tilde_path "${HOOK_SOURCE}") $(to_tilde_path "${target}")")"
    rm -f "${target}" && ln -s "${HOOK_SOURCE}" "${target}"
  else
    [ -n "${quiet}" ] || action "Writing $(code "$(to_tilde_path "${target}")")"
    rm -f "${target}" && hook_content > "${target}" && chmod +x "${target}"
  fi
}

step_install_hook() {
  local hook_dir="${template_dir}/hooks"
  local display_hook_path title

  hook_path="${hook_dir}/prepare-commit-msg"
  display_hook_path="$(to_tilde_path "${hook_path}")"
  if links_hooks; then
    title="Link $(code "${display_hook_path}") to $(code "$(to_tilde_path "${HOOK_SOURCE}")")"
  else
    title="Write $(code "${display_hook_path}")"
  fi

  if hook_is_current "${hook_path}"; then
    heading 5 "${title}"
    echo
    echo "  $(code "${hook_path}") ${C_GREEN}is already up to date.${C_RESET}"
    return 0
  elif [ ! -e "${hook_path}" ] && [ ! -L "${hook_path}" ]; then
    if ! prompt_step 5 "${title}"; then
      abort
    fi
  elif is_hook_link "${hook_path}" || is_installer_hook "${hook_path}"; then
    if links_hooks; then
      title="Update the hook and link $(code "${display_hook_path}") to $(code "$(to_tilde_path "${HOOK_SOURCE}")")"
    else
      title="Update $(code "${display_hook_path}")"
    fi
    if ! prompt_step 5 "${title}"; then
      abort
    fi
  else
    # A hook from another source. It is not replaced without an explicit yes.
    heading 5 "${title}"
    echo
    warning "$(code "${hook_path}")${C_YELLOW} already exists and was not written by this installer."
    echo "  ${C_YELLOW}Overwriting removes your existing hook.${C_RESET}"
    echo
    if ! ask "Overwrite the existing hook?" n; then
      echo "  ${C_YELLOW}Kept the existing hook. The commit message hook is not installed.${C_RESET}"
      echo "  ${C_RED}To install it, move the existing hook away or merge both by hand, then re-run this script. Aborting.${C_RESET}"
      exit 1
    fi
  fi

  if ! mkdir -p "${hook_dir}"; then
    die "failed to create $(code "${hook_dir}"). Aborting."
  fi
  if links_hooks && ! write_hook_source; then
    die "failed to write $(code "${HOOK_SOURCE}"). Aborting."
  fi
  if ! place_hook "${hook_path}"; then
    die "failed to write $(code "${hook_path}"). Aborting."
  fi
  echo "  ${C_GREEN}Done.${C_RESET}"
}

# Prints the hooks directory of the repository in the current directory and of
# each repository in the directories of --repos, each once. A repository with
# its own core.hooksPath keeps its hooks and is left out.
find_repo_hook_dirs() {
  local dir git_path repo common_dir
  {
    git rev-parse --show-toplevel 2>/dev/null || true
    for dir in ${repo_dirs[@]+"${repo_dirs[@]}"}; do
      dir="$(resolve_template_dir "${dir}")"
      [ -d "${dir}" ] || continue
      find "${dir}" -maxdepth "${REPO_SEARCH_DEPTH}" \( -name node_modules -o -name vendor \) -prune \
        -o -name .git -prune -print 2>/dev/null |
        while IFS= read -r git_path; do
          dirname "${git_path}"
        done
    done
  } | while IFS= read -r repo; do
    [ -n "${repo}" ] || continue
    if git -C "${repo}" config --local --get core.hooksPath >/dev/null 2>&1; then
      continue
    fi
    # Worktrees and submodules resolve to the git directory that keeps the hooks.
    common_dir="$(cd "${repo}" 2>/dev/null && cd "$(git rev-parse --git-common-dir 2>/dev/null)" 2>/dev/null && pwd)" ||
      continue
    printf '%s/hooks\n' "${common_dir}"
  done | sort -u
}

# The number of repositories that step 6 lists by name.
REPO_LIST_LIMIT=10

step_link_repos() {
  local hooks_dir hook title
  local linked=0
  local shown=0
  local failed=0
  local candidates=()

  if links_hooks; then
    title="Link the hook in your repositories"
  else
    title="Update the hook in your repositories"
  fi

  while IFS= read -r hooks_dir; do
    hook="${hooks_dir}/prepare-commit-msg"
    if hook_is_current "${hook}"; then
      linked=$((linked + 1))
    elif is_hook_link "${hook}" || is_installer_hook "${hook}"; then
      candidates+=("${hook}")
    fi
  done < <(find_repo_hook_dirs)

  heading 6 "${title}"
  echo
  if [ "${#candidates[@]}" -eq 0 ]; then
    if [ "${#repo_dirs[@]}" -eq 0 ] && [ "${linked}" -eq 0 ]; then
      echo "  No repository to check. Pass $(code "--repos DIR") to look for repositories in DIR."
    elif links_hooks; then
      echo "  ${C_GREEN}No repository has an old copy of the hook${C_RESET} (${linked} linked)."
    else
      echo "  ${C_GREEN}No repository has an old copy of the hook${C_RESET} (${linked} up to date)."
    fi
    return 0
  fi

  if links_hooks; then
    echo "  These repositories have a copy of the hook from this installer. A link"
    echo "  instead of the copy gets them every future update of the hook:"
  else
    echo "  These repositories have an old copy of the hook from this installer:"
  fi
  echo
  for hook in "${candidates[@]}"; do
    if [ "${shown}" -ge "${REPO_LIST_LIMIT}" ]; then
      echo "  ... and $((${#candidates[@]} - shown)) more"
      break
    fi
    echo "  $(code "$(to_tilde_path "${hook}")")"
    shown=$((shown + 1))
  done
  echo
  if ! ask "Run this step?" y; then
    echo "  ${C_YELLOW}Skipped.${C_RESET}"
    return 0
  fi
  if links_hooks; then
    action "$(code "ln -sf $(to_tilde_path "${HOOK_SOURCE}") <repository>/.git/hooks/prepare-commit-msg")"
  else
    action "Writing $(code "<repository>/.git/hooks/prepare-commit-msg")"
  fi
  for hook in "${candidates[@]}"; do
    if ! place_hook "${hook}" quiet; then
      warning "failed to write $(code "${hook}")${C_YELLOW}."
      failed=$((failed + 1))
    fi
  done
  echo "  ${C_GREEN}Done${C_RESET} ($((${#candidates[@]} - failed)) of ${#candidates[@]} repositories)."
}

step_editor() {
  local editor kind config_path display_config_path
  local new_file_content=''

  editor="$(detect_editor)"
  kind="$(editor_kind "${editor}")"

  if [ "${kind}" = other ]; then
    heading 7 "Check how your editor aborts a commit"
    echo
    echo "  ${C_YELLOW}Editor does not look like Vim (git uses${C_RESET} $(code "${editor:-no editor}")${C_YELLOW}).${C_RESET}"
    echo
    echo "  ${C_YELLOW}${C_BOLD}BE CAREFUL when using other editors:${C_RESET}"
    echo "  ${C_YELLOW}If you intend to abort the commit, first comment out the${C_RESET}"
    echo "  ${C_YELLOW}generated commit message, otherwise the commit WILL proceed.${C_RESET}"
    return 0
  fi

  if ! config_path="$(editor_config_path "${kind}")"; then
    heading 7 "Abort commit on :q! (only for Vim users)"
    echo
    echo "  ${C_YELLOW}Neovim uses${C_RESET} $(code "init.lua")${C_YELLOW} here, so this script cannot add the snippet.${C_RESET}"
    echo "  ${C_YELLOW}To abort a commit on :q, add the snippet by hand, for example inside${C_RESET} $(code "vim.cmd([[ ... ]])")${C_YELLOW}:${C_RESET}"
    echo
    print_snippet "${VIM_SNIPPET}"
    return 0
  fi
  display_config_path="$(to_tilde_path "${config_path}")"

  heading 7 "Append snippet to $(code "${display_config_path}") to abort commit on :q! (only for Vim users)"
  echo
  if [ -f "${config_path}" ] && grep -q 'augroup GitCommitAbort' "${config_path}"; then
    echo "  ${C_GREEN}Snippet is already present in${C_RESET} $(code "${config_path}")${C_GREEN}; no change needed.${C_RESET}"
    return 0
  fi

  if [ -f "${config_path}" ]; then
    echo "  Will append the following to $(code "${config_path}"):"
  else
    echo "  Will create $(code "${config_path}") with the following content:"
    if [ "${kind}" = vim ]; then
      new_file_content="${VIM_DEFAULTS_SNIPPET}"$'\n\n'
    fi
  fi
  echo
  print_snippet "${new_file_content}${VIM_SNIPPET}"
  echo
  echo "  ${C_YELLOW}${C_BOLD}INFO:${C_RESET}${C_YELLOW} This helps prevent accidentally committing a generated message.${C_RESET}"
  echo
  if ! ask "Run this step?" n; then
    echo "  ${C_YELLOW}Skipped.${C_RESET}"
    return 0
  fi

  if [ -f "${config_path}" ]; then
    action "Appending snippet to $(code "${config_path}")"
    # Start on a new line, also when the file does not end with one.
    if [ -n "$(tail -c 1 "${config_path}")" ]; then
      printf '\n' >> "${config_path}"
    fi
    printf '\n%s\n' "${VIM_SNIPPET}" >> "${config_path}"
  else
    action "Creating $(code "${config_path}")"
    mkdir -p "$(dirname "${config_path}")"
    printf '%s\n' "${new_file_content}${VIM_SNIPPET}" > "${config_path}"
  fi
  echo "  ${C_GREEN}Done.${C_RESET}"
}

step_manual() {
  heading 8 "Manual action required"
  echo
  echo "  ${C_BOLD}Run $(code "git init")${C_BOLD} in each repository where you want this hook template to apply.${C_RESET}"
  echo
  echo "  $(code "git init") does not replace a hook that a repository already has."
  if links_hooks; then
    echo "  To link the hook in such a repository, run this command in the repository:"
    echo
    echo "  $(code "ln -sf $(to_tilde_path "${HOOK_SOURCE}") \"\$(git rev-parse --git-path hooks)/prepare-commit-msg\"")"
  else
    echo "  To update the hook of such a repository, run this command in the repository:"
    echo
    echo "  $(code "cp $(to_tilde_path "${hook_path}") \"\$(git rev-parse --git-path hooks)/\"")"
  fi
  echo
  echo "  To do this for all repositories in a directory that have a copy of the"
  echo "  hook from this installer, run the installer again with $(code "--repos DIR")."
  echo
}

main() {
  setup_colors
  parse_args "$@"
  detect_platform
  check_requirements
  trap cleanup EXIT

  echo "${C_GREEN}Installer is running on $(platform_title).${C_RESET}"
  echo "${C_DIM}All changes will be shown before they are applied.${C_RESET}"

  step_install_cmai
  step_api_key
  step_configure_cmai
  step_template_dir
  step_install_hook
  step_link_repos
  step_editor
  step_manual
}

