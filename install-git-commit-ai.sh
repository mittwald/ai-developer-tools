# The tilde in the next two functions is literal text, as git config stores it.
# shellcheck disable=SC2088
to_tilde_path() {
  local p="$1"
  if [ "$p" = "$HOME" ]; then
    printf '~'
  elif [ "${p#"$HOME"/}" != "$p" ]; then
    printf '~/%s' "${p#"$HOME"/}"
  else
    printf '%s' "$p"
  fi
}

# shellcheck disable=SC2088
resolve_template_dir() {
  local p="$1"
  case "$p" in
    "~") printf '%s\n' "${HOME}" ;;
    "~/"*) printf '%s/%s\n' "${HOME}" "${p#"~/"}" ;;
    *) printf '%s\n' "$p" ;;
  esac
}

prompt_template_dir() {
  local initial="$1"
  local input=''
  local resolved=''

  while true; do
    if is_interactive; then
      printf '  %sTemplate directory:%s ' "${C_BOLD}${C_BLUE}" "${C_RESET}"
      read -r -e -i "${initial}" input < /dev/tty || true
    else
      printf '  %sTemplate directory:%s %s\n' "${C_BOLD}${C_BLUE}" "${C_RESET}" "$(code "${initial}")"
      input="${initial}"
    fi

    [ -z "${input}" ] && input="${initial}"
    resolved="$(resolve_template_dir "${input}")"
    if [ "${resolved#/}" = "${resolved}" ]; then
      error "template directory must be an absolute path."
      if is_interactive; then
        continue
      fi
      return 1
    fi

    template_dir="${resolved}"
    return 0
  done
}

