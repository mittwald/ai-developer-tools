# Asks a yes/no question. $1 = question, $2 = default answer (y or n).
ask() {
  local question="$1"
  local default="$2"
  local hint='[y/N]'
  local answer=''
  if [ "${default}" = y ]; then
    hint='[Y/n]'
  fi
  printf '  %s%s %s:%s ' "${C_BOLD}${C_BLUE}" "${question}" "${hint}" "${C_RESET}"
  if is_interactive; then
    read -r answer < /dev/tty || true
  elif [ "${default}" = y ]; then
    echo 'Y'
  else
    echo 'N'
  fi
  if [ -z "${answer}" ]; then
    answer="${default}"
  fi
  case "${answer}" in
    y|Y|yes|Yes|YES) return 0 ;;
    *) return 1 ;;
  esac
}

prompt_step() {
